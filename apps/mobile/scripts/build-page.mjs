// Bundles the reader page's script (src/page/, with @klipstack/anchor) into a string the app puts
// in the page: src/lib/reader-page.generated.ts, committed. Metro takes it as any module; nothing
// runs at build time. `pnpm build:page` after changing src/page/; a test fails while it is stale.
import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { build } from "esbuild"

const entry = fileURLToPath(new URL("../src/page/entry.ts", import.meta.url))
export const OUTPUT = fileURLToPath(new URL("../src/lib/reader-page.generated.ts", import.meta.url))

/** The page script as the page runs it: one function, run once, in WebKit (iOS 16.4 on). */
export async function bundlePage() {
	const result = await build({
		entryPoints: [entry],
		bundle: true,
		write: false,
		format: "iife",
		target: "safari16.4",
		legalComments: "none",
		logLevel: "silent",
	})
	const script = result.outputFiles[0].text
	// Inside a <script> element, these would end it or start a comment.
	if (/<\/script|<!--/i.test(script)) throw new Error("The page script holds </script or <!--")
	return script
}

/** The generated module: the script, and its hash for the page's Content-Security-Policy. */
export async function generatedModule() {
	const script = await bundlePage()
	const hash = createHash("sha256").update(script).digest("base64")
	return `// Generated by scripts/build-page.mjs from src/page/ (\`pnpm build:page\`). Do not edit.

/** The reader page's script (src/page/reader-page.ts), bundled with @klipstack/anchor. */
export const pageScript = ${JSON.stringify(script)}

/** Its hash, which the page's Content-Security-Policy allows. */
export const pageScriptHash = "sha256-${hash}"
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const next = await generatedModule()
	let current = ""
	try {
		current = readFileSync(OUTPUT, "utf8")
	} catch {
		// Not generated yet.
	}
	if (next === current) console.log("reader-page.generated.ts is up to date")
	else {
		writeFileSync(OUTPUT, next)
		console.log("wrote src/lib/reader-page.generated.ts")
	}
}
